.module d7_led
.area HOME (CODE)
.area CSEG (CODE)
.area HOME (CODE)
base:
 ljmp normal_hook
; Private state in loaded code RAM; no ROM-owned scratch address.
phase:
 .db 0
; Build marker at CC04.
 .ascii "D7LED01"
 .ds (0x30-(.-base))
; CBD4 bit3 replaces timer ISR body. Outer ROM ISR saves all registers.
 ljmp timer_hook
 .ds (0x40-(.-base))
timer_hook:
; Exact original D7 timer body at ROM 60C0..60D6.
 mov dptr,#0xC8FA
 lcall 0x8050
 mov dptr,#0xC8FC
 lcall 0x8050
 mov dptr,#0xC8FE
 lcall 0x8050
 mov dptr,#0xF005
 clr a
 movx @dptr,a
; One nonblocking private counter increment per timer interrupt.
 mov dptr,#phase
 movx a,@dptr
 inc a
 movx @dptr,a
 ret
 .ds (0x80-(.-base))
normal_hook:
 push psw
 push acc
 push dpl
 push dph
; Default capture selection 720p; apps still select format and frame rate.
 mov dptr,#0xC0A8
 mov a,#6
 movx @dptr,a
 mov dptr,#0xC2C3
 movx @dptr,a
; GPIO0: active-low LED, P2.0 value, P3.0 output enable (active low).
; Observed IRAM20: 84 with signal, 94 without. Bit4 = no signal.
 jb 0x04,led_off
 mov dptr,#phase
 movx a,@dptr
 mov c,acc.7
 mov 0xA0,c
 sjmp led_direction
led_off:
 setb 0xA0
led_direction:
 clr 0xB0
; Preserve flags and inputs for all normal events.
 cjne r7,#8,done
 pop dph
 pop dpl
 pop acc
 pop psw
; D7 event8 supplies EDID through generic CODE pointer FF:CD:00.
 mov r3,#0xFF
 mov r2,#0xCD
 mov r1,#0
 ljmp 0x73F7
 done:
 pop dph
 pop dpl
 pop acc
 pop psw
 ret
 .ds (0x100-(.-base))
